// macOS has no clipboard change notification, so the channel polls
// NSPasteboard's changeCount (an integer read) and reads the text only when
// it changes. AppKit is called through the Objective-C runtime with purego:
// no cgo.
//
// Pasteboard privacy: recent macOS releases can alert the user when a
// background process reads the pasteboard. Whether that applies to this
// LaunchAgent, and whether a PPPC/MDM profile avoids it, is to be confirmed
// on hardware (#266); the channel itself only reads after a change.
const darwinPoll = 250 * time.Millisecond

const (
	utf8Type      = "public.utf8-plain-text"
	concealedType = "org.nspasteboard.ConcealedType"
	transientType = "org.nspasteboard.TransientType"
	autoGenType   = "org.nspasteboard.AutoGeneratedType"
)

var (
	appkitOnce sync.Once
	errAppKit  error

	selAlloc, selInit, selDrain, selGeneralPasteboard, selChangeCount, selStringForType,
	selClearContents, selSetStringForType, selTypes, selContainsObject, selStringWithUTF8,
	selUTF8String, selSharedWorkspace, selFrontmostApplication, selBundleIdentifier,
	selBundleURL, selPath, selLocalizedName objc.SEL
)

func loadAppKit() error {
	appkitOnce.Do(func() {
		if _, err := purego.Dlopen("/System/Library/Frameworks/AppKit.framework/AppKit", purego.RTLD_GLOBAL|purego.RTLD_NOW); err != nil {
			errAppKit = fmt.Errorf("load AppKit: %w", err)
			return
		}
		for _, s := range []struct {
			sel  *objc.SEL
			name string
		}{
			{&selAlloc, "alloc"}, {&selInit, "init"}, {&selDrain, "drain"},
			{&selGeneralPasteboard, "generalPasteboard"}, {&selChangeCount, "changeCount"},
			{&selStringForType, "stringForType:"}, {&selClearContents, "clearContents"},
			{&selSetStringForType, "setString:forType:"}, {&selTypes, "types"},
			{&selContainsObject, "containsObject:"}, {&selStringWithUTF8, "stringWithUTF8String:"},
			{&selUTF8String, "UTF8String"}, {&selSharedWorkspace, "sharedWorkspace"},
			{&selFrontmostApplication, "frontmostApplication"}, {&selBundleIdentifier, "bundleIdentifier"},
			{&selBundleURL, "bundleURL"}, {&selPath, "path"}, {&selLocalizedName, "localizedName"},
		} {
			*s.sel = objc.RegisterName(s.name)
		}
	})
	return errAppKit
}

func pasteboard() objc.ID {
	return objc.ID(objc.GetClass("NSPasteboard")).Send(selGeneralPasteboard)
}

func nsString(s string) objc.ID {
	return objc.ID(objc.GetClass("NSString")).Send(selStringWithUTF8, s)
}

func goString(id objc.ID) string {
	if id == 0 {
		return ""
	}
	return objc.Send[string](id, selUTF8String)
}

// withPool runs fn in an autorelease pool, so per-poll objects are freed.
func withPool(fn func()) {
	pool := objc.ID(objc.GetClass("NSAutoreleasePool")).Send(selAlloc).Send(selInit)
	defer pool.Send(selDrain)
	fn()
}

type darwinChannel struct{}

// New returns the clipboard channel for this platform.
func New() channel.Channel { return darwinChannel{} }

func (darwinChannel) Name() string { return Name }

func (darwinChannel) Supported() channel.Capability {
	if err := loadAppKit(); err != nil {
		return channel.Unsupported("no_appkit")
	}
	ok := false
	withPool(func() { ok = pasteboard() != 0 })
	if !ok {
		return channel.Unsupported("no_pasteboard")
	}
	return channel.Supported()
}

// Run polls the pasteboard until ctx ends.
func (c darwinChannel) Run(ctx context.Context, p *policy.Compiled, sink channel.EventSink) error {
	if !c.Supported().Supported {
		return channel.ErrUnsupported
	}
	// Autorelease pools belong to a thread.
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()

	w := &pbWatcher{p: p, sink: sink, lastCount: -1}
	t := time.NewTicker(darwinPoll)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-t.C:
			withPool(w.check)
		}
	}
}

type pbWatcher struct {
	p    *policy.Compiled
	sink channel.EventSink

	lastCount int
	ownCount  int
	lastKey   [32]byte // last text + source app scanned
	lastBlock bool
}

func (w *pbWatcher) check() {
	pb := pasteboard()
	count := objc.Send[int](pb, selChangeCount)
	if count == w.lastCount {
		return
	}
	w.lastCount = count
	if count == w.ownCount {
		return // our placeholder
	}
	if w.p.Modules.Clipboard.IgnoreConcealed && hasAnyType(pb, concealedType, transientType, autoGenType) {
		return
	}
	text := goString(pb.Send(selStringForType, nsString(utf8Type)))
	if text == "" {
		return
	}
	src := frontmostApp()
	key := dedupeKey(text, src)
	if key == w.lastKey && !w.lastBlock {
		return // same text from the same app
	}
	d := Decide(w.p, text, src, time.Now())
	w.lastKey, w.lastBlock = key, d.Block
	if d.Block && !w.replace(pb, count, d.Message) {
		// A newer copy arrived, or the write failed: the scanned content
		// may still be pasteable, so don't claim it was blocked.
		markMonitored(d.Events)
	}
	for _, ev := range d.Events {
		w.sink.Emit(ev)
	}
}

// replace swaps the content seen at changeCount scanned for msg, unless a
// newer copy has arrived meanwhile (it gets its own check).
func (w *pbWatcher) replace(pb objc.ID, scanned int, msg string) bool {
	if objc.Send[int](pb, selChangeCount) != scanned {
		return false
	}
	objc.Send[int](pb, selClearContents)
	if !objc.Send[bool](pb, selSetStringForType, nsString(msg), nsString(utf8Type)) {
		return false
	}
	// Clipboard managers skip transient content.
	objc.Send[bool](pb, selSetStringForType, nsString(""), nsString(transientType))
	w.ownCount = objc.Send[int](pb, selChangeCount)
	w.lastCount = w.ownCount
	return true
}

// hasAnyType reports whether the pasteboard offers one of the types.
func hasAnyType(pb objc.ID, types ...string) bool {
	offered := pb.Send(selTypes)
	if offered == 0 {
		return false
	}
	for _, t := range types {
		if objc.Send[bool](offered, selContainsObject, nsString(t)) {
			return true
		}
	}
	return false
}

// frontmostApp is the app in front when the copy was seen: the best signal
// macOS gives for where clipboard content came from.
func frontmostApp() events.SourceApp {
	ws := objc.ID(objc.GetClass("NSWorkspace")).Send(selSharedWorkspace)
	app := ws.Send(selFrontmostApplication)
	if app == 0 {
		return events.SourceApp{}
	}
	return events.SourceApp{
		Name:     goString(app.Send(selLocalizedName)),
		BundleID: goString(app.Send(selBundleIdentifier)),
		Path:     goString(app.Send(selBundleURL).Send(selPath)),
	}
}
